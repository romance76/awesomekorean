    private static ?array $ids = null;

    /** 분류 slug (근거가 약하면 society) */
    public static function guess(string $title, ?string $summary = null): string
    {
        $summary = (string) $summary;
        $best = 'society';
        $bestScore = 1;   // 이 점수를 넘어야(= 제목 키워드 1개 이상 또는 요약 키워드 2개 이상) 사회가 아닌 분류로 정함
        foreach (self::RULES as $slug => $words) {
            $score = 0;
            foreach ($words as $w) {
                if (mb_strpos($title, $w) !== false) $score += 3;
                if ($summary !== '' && mb_strpos($summary, $w) !== false) $score += 1;
            }
            if ($score > $bestScore) { $best = $slug; $bestScore = $score; }
        }
        return $best;
    }

    public static function categoryId(string $title, ?string $summary = null): ?int
    {
        self::$ids ??= NewsCategory::pluck('id', 'slug')->all();
        return self::$ids[self::guess($title, $summary)] ?? null;
    }
